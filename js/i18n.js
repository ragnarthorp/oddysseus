  function fill(s, vars) {
    return String(s).replace(/\{(\w+)(?:\|(\w+))?\}/g, (m, k, w) => {
      if (!vars || !(k in vars)) return m;
      return w ? `${vars[k]} ${word(Number(vars[k]), w)}` : String(vars[k]);
    });
  }
  function t(key, vars) {
    const s = (D[lang] && key in D[lang]) ? D[lang][key] : D.is[key];
    if (s == null) return key;
    return fill(s, vars);
  }
