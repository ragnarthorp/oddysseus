  /* Skrifar þýðingar yfir föst atriði í DOM. Allt sem textContent – aldrei innerHTML. */
  function applyHtml(doc) {
    const list = HTML[lang];
    if (!list) return;
    for (const [sel, kind, val] of list) {
      let els;
      try { els = doc.querySelectorAll(sel); } catch (e) { continue; }
      for (const el of els) {
        if (kind === 'text') el.textContent = val;
        else if (kind === 'firstText') { const n = Array.from(el.childNodes).find(c => c.nodeType === 3 && c.textContent.trim()); if (n) n.textContent = val; }
        else if (kind === 'html-safe') {
          el.textContent = '';
          for (const part of val) {
            if (typeof part === 'string') el.appendChild(doc.createTextNode(part));
            else { const e = doc.createElement(part[0]); e.textContent = part[1]; if (part[2]) e.className = part[2]; el.appendChild(e); }
          }
        } else el.setAttribute(kind, val);
      }
    }
  }

